function readStoredLanguage() {
  try {
    return window.sessionStorage.getItem('soltane-lang');
  } catch {
    return null;
  }
}

function persistLanguage(lang) {
  try {
    window.sessionStorage.setItem('soltane-lang', lang);
  } catch {
    // Storage may be unavailable in privacy-restricted browsing contexts.
  }
}

export function setLang(lang = 'fr') {
  const nextLang = lang === 'ar' ? 'ar' : 'fr';
  const html = document.documentElement;
  const dictionary = I18N[nextLang];

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.textContent = dictionary[key];
    }
  });

  document.querySelectorAll('[data-i18n-ph]').forEach((element) => {
    const key = element.dataset.i18nPh;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute('placeholder', dictionary[key]);
    }
  });

  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const key = element.dataset.i18nAria;
    if (Object.prototype.hasOwnProperty.call(dictionary, key)) {
      element.setAttribute('aria-label', dictionary[key]);
    }
  });

  html.lang = nextLang;
  html.dir = nextLang === 'ar' ? 'rtl' : 'ltr';
  html.dataset.lang = nextLang;
  document.title = html.dataset.page === 'rooms'
    ? TITLES[nextLang === 'ar' ? 'roomsAr' : 'roomsFr']
    : html.dataset.page === 'experiences'
      ? TITLES[nextLang === 'ar' ? 'experiencesAr' : 'experiencesFr']
      : html.dataset.page === 'gallery'
        ? TITLES[nextLang === 'ar' ? 'galleryAr' : 'galleryFr']
        : html.dataset.page === 'contact'
          ? TITLES[nextLang === 'ar' ? 'contactAr' : 'contactFr']
          : TITLES[nextLang];

  document.getElementById('lang-fr')?.setAttribute('aria-pressed', String(nextLang === 'fr'));
  document.getElementById('lang-ar')?.setAttribute('aria-pressed', String(nextLang === 'ar'));

  persistLanguage(nextLang);
  document.dispatchEvent(new CustomEvent('soltane:languagechange', { detail: { lang: nextLang } }));
  return nextLang;
}

export function initLang() {
  const stored = readStoredLanguage();
  return setLang(stored === 'ar' ? 'ar' : 'fr');
}
